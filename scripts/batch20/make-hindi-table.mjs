#!/usr/bin/env node
// Batch 20 - writes docs/review/batch20/HINDI_STRINGS.md from src/lib/i18n/mitraStrings.js (key, Hindi, English, where shown).
import { writeFileSync } from 'node:fs'
import { mitraStrings } from '../../src/lib/i18n/mitraStrings.js'

const where = (k) => {
  if (k.startsWith('mitra_field') || k === 'mitra_none') return 'Sign-up form (optional dropdown)'
  if (k === 'adm_p_mitra' || k === 'mitra_pay_outside') return 'Admin > People > Kissan Mitra (panel name, search, reminder line)'
  if (k.startsWith('mitra_sum_') || ['mitra_add', 'mitra_csv', 'mitra_empty', 'mitra_retry'].includes(k)) return 'Admin: top strip and buttons'
  if (k.startsWith('mitra_c_') || ['mitra_active', 'mitra_inactive', 'mitra_switch_label', 'mitra_rate_not_set'].includes(k) || k.startsWith('mitra_btn_')) return 'Admin: a Mitra card'
  if (k.startsWith('mitra_f_') || k.startsWith('mitra_form_') || ['mitra_save', 'mitra_saved', 'mitra_back'].includes(k) || k.startsWith('mitra_err_')) return 'Admin: add / edit form'
  if (k.startsWith('err_mitra_')) return 'Admin: error messages from the database'
  if (k.startsWith('mitra_pay_')) return 'Admin: mark-paid dialog'
  if (k.startsWith('mitra_ledger_') || k === 'mitra_close') return 'Admin: payments (ledger) dialog'
  return 'Admin: registrations view'
}
const cell = (s) => String(s).replace(/\|/g, '\\|')
const rows = Object.entries(mitraStrings).map(([k, v]) => `| \`${k}\` | ${cell(v.hi)} | ${cell(v.en)} | ${where(k)} |`)
writeFileSync('docs/review/batch20/HINDI_STRINGS.md', `# Batch 20 - Hindi and English strings (Kissan Mitra)\n\nSpelling: Hindi **किसान मित्र**, English **Kissan Mitra**. \`{x}\` marks a value the screen fills in. Source: \`src/lib/i18n/mitraStrings.js\` (generated by \`scripts/batch20/make-hindi-table.mjs\`).\n\n| Key | Hindi | English | Where shown |\n|---|---|---|---|\n${rows.join('\n')}\n`)
console.log(`${rows.length} strings written`)
