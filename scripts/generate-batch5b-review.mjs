#!/usr/bin/env node
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const raw = JSON.parse(readFileSync(join(root, 'docs/research/qa_raw/batch5b.json'), 'utf8'))
const evidence = JSON.parse(readFileSync(join(root, 'docs/research/qa_raw/batch5b.evidence.json'), 'utf8'))
const sources = new Map(raw.sources.map(source => [source.id, source]))
const snapshots = readdirSync(join(root, 'docs/research/source_snapshots')).filter(name => name.endsWith('.txt')).map(name => readFileSync(join(root, 'docs/research/source_snapshots', name), 'utf8'))
const cell = value => String(value ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim()
const answer = q => [q.short_hi, ...(q.blocks || []).flatMap(block => [block.text, ...(block.items || []).map(item => item.text)])].filter(Boolean).join(' ')
const snapshot = url => snapshots.find(text => text.split('\n', 1)[0].includes(url) && /\| HTTP 200 \| fetched at (?![^|]*00:00:00Z)[^|]+Z \| sha256 [a-f0-9]{64} \|/i.test(text.split('\n', 1)[0]))
const when = text => text.split('\n', 1)[0].match(/fetched at ([^|]+Z)/i)?.[1] || 'missing'
let markdown = '# Batch 5B review copy\n\nByline: **Team Kissan Sahyog**. Generated by `scripts/generate-batch5b-review.mjs`.\n\n| Slug | Hindi question | Hindi answer | Publisher | URL | Fetched at (UTC) | Verbatim quote(s) | Verdict |\n|---|---|---|---|---|---|---|---|\n'
for (const q of raw.qas) {
  const rows = evidence[q.slug] || []
  const first = sources.get(rows[0]?.source || q.sources?.[0])
  const page = first && snapshot(first.url)
  const supported = rows.length && page && rows.every(row => page.includes(row.quote))
  markdown += `| ${cell(q.slug)} | ${cell(q.question_hi)} | ${cell(answer(q))} | ${cell(first?.publisher)} | ${cell(first?.url)} | ${cell(page && when(page))} | ${cell(rows.map(row => row.quote).join(' / '))} | ${supported ? 'SUPPORTED' : 'PARTLY'} |\n`
}
writeFileSync(join(root, 'docs/review/QA_BATCH5B_FOR_REVIEW.md'), markdown)
console.log(`Wrote review table for ${raw.qas.length} Q&As.`)
